#!/usr/bin/env python3
"""Write offline-manifest.js: the files the service worker (sw.js) saves for offline use.

The version is a hash of every listed file, so any change to the app makes
visitors' browsers download the new version in the background.

Run it after anything in the app changes (audio, images, js, css...):
    python3 tools/build_offline.py
"""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "offline-manifest.js"
PATTERNS = [
    "index.html",
    "manifest.webmanifest",
    "css/*.css",
    "js/*.js",
    "fonts/*.woff2",
    "icons/*",
    "images/**/*.svg",
    "audio/**/*.mp3",
]


def main():
    files = sorted({path for pattern in PATTERNS for path in ROOT.glob(pattern) if path.is_file()})
    digest = hashlib.sha256((ROOT / "sw.js").read_bytes())
    for path in files:
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(path.read_bytes())
    assets = [path.relative_to(ROOT).as_posix() for path in files]
    size = sum(path.stat().st_size for path in files)

    OUT.write_text(
        "// Generated by tools/build_offline.py. Do not edit by hand.\n"
        f"self.OFFLINE_VERSION = '{digest.hexdigest()[:12]}';\n"
        f"self.OFFLINE_ASSETS = {json.dumps(assets, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(assets)} files, {size / 1024 / 1024:.1f} MB")


if __name__ == "__main__":
    main()
