#!/usr/bin/env python3
"""Rebuild everything the page needs besides the audio. Run it after any change.

1. js/scenes.js          per-paragraph illustrations (images/<book>/ch<N>/pNN.svg)
2. js/vocabulary.js      each book's vocabulary words, from content/stories.json
3. pdf/<book>.pdf        printable books (needs Node and Google Chrome; skipped otherwise)
4. offline-manifest.js   files the service worker saves for offline use (last,
                         so its version hash covers the new PDFs too)

Usage:
    python3 tools/build.py            # everything
    python3 tools/build.py --no-pdf   # keep the current PDFs
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STORIES = ROOT / "content" / "stories.json"
OFFLINE_PATTERNS = [
    "index.html",
    "manifest.webmanifest",
    "css/*.css",
    "js/*.js",
    "fonts/*.woff2",
    "icons/*",
    "images/**/*.svg",
    "audio/**/*.mp3",
    "pdf/*.pdf",
]


def write_js(path, comment, variable, value):
    path.write_text(
        f"// Generated by tools/build.py ({comment}). Do not edit by hand.\n"
        f"{variable} = {json.dumps(value, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )


def build_scenes(books):
    """A paragraph without its own scene reuses the previous one; chapters with no
    scenes at all fall back to images/<book>/ch<N>.svg in the page."""
    index = {}
    for book in books:
        for number, chapter in enumerate(book["chapters"], start=1):
            folder = ROOT / "images" / book["id"] / f"ch{number}"
            found = {}
            for svg in folder.glob("p*.svg") if folder.is_dir() else []:
                match = re.fullmatch(r"p(\d+)\.svg", svg.name)
                if match:
                    found[int(match.group(1))] = svg.relative_to(ROOT).as_posix()
            if not found:
                continue
            scenes, current = [], f"images/{book['id']}/ch{number}.svg"
            for paragraph in range(1, len(chapter["paragraphs"]) + 1):
                current = found.get(paragraph, current)
                scenes.append(current)
            index[f"{book['id']}/{number}"] = scenes
    write_js(ROOT / "js" / "scenes.js", "scene of every paragraph", "window.SCENES", index)
    print(f"js/scenes.js: {sum(len(s) for s in index.values())} paragraphs with scenes")


def build_vocabulary(books):
    vocabulary = {book["id"]: book["vocabulary"] for book in books if "vocabulary" in book}
    write_js(ROOT / "js" / "vocabulary.js", "vocabulary of every book", "window.VOCABULARY", vocabulary)
    print(f"js/vocabulary.js: {sum(len(v['words']) for v in vocabulary.values())} words")


def build_pdfs():
    if not shutil.which("node"):
        print("pdf/: skipped (Node is not installed); keeping the current PDFs")
        return
    result = subprocess.run(["node", str(ROOT / "tools" / "build_pdfs.mjs")], cwd=ROOT)
    if result.returncode != 0:
        print("pdf/: FAILED, keeping the current PDFs (see the error above)")


def build_offline_manifest():
    files = sorted({p for pattern in OFFLINE_PATTERNS for p in ROOT.glob(pattern) if p.is_file()})
    digest = hashlib.sha256((ROOT / "sw.js").read_bytes())
    for path in files:
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(path.read_bytes())
    (ROOT / "offline-manifest.js").write_text(
        "// Generated by tools/build.py (files saved for offline use). Do not edit by hand.\n"
        f"self.OFFLINE_VERSION = '{digest.hexdigest()[:12]}';\n"
        f"self.OFFLINE_ASSETS = {json.dumps([p.relative_to(ROOT).as_posix() for p in files], indent=2)};\n",
        encoding="utf-8",
    )
    size = sum(p.stat().st_size for p in files)
    print(f"offline-manifest.js: {len(files)} files, {size / 1024 / 1024:.1f} MB")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-pdf", action="store_true", help="don't regenerate the PDFs")
    args = parser.parse_args()

    books = json.loads(STORIES.read_text(encoding="utf-8"))["books"]
    build_scenes(books)
    build_vocabulary(books)
    if not args.no_pdf:
        build_pdfs()
    build_offline_manifest()


if __name__ == "__main__":
    main()
