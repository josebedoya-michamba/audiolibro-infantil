#!/usr/bin/env python3
"""Write js/scenes.js: the per-paragraph illustrations of every chapter.

Scenes live at images/<book>/ch<N>/p<NN>.svg (p01 = first paragraph). A chapter
paragraph without its own scene reuses the previous one, so a chapter only
needs scenes where the picture should change. Chapters with no scenes at all
fall back to images/<book>/ch<N>.svg in the page.

Usage: python3 tools/build_scene_index.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STORIES = ROOT / "content" / "stories.json"
OUT = ROOT / "js" / "scenes.js"


def main():
    books = json.loads(STORIES.read_text(encoding="utf-8"))["books"]
    index = {}
    for book in books:
        for number, chapter in enumerate(book["chapters"], start=1):
            folder = ROOT / "images" / book["id"] / f"ch{number}"
            found = {}
            for svg in folder.glob("p*.svg") if folder.is_dir() else []:
                match = re.fullmatch(r"p(\d+)\.svg", svg.name)
                if match:
                    found[int(match.group(1))] = svg.relative_to(ROOT).as_posix()
            if not found:
                continue
            scenes, current = [], f"images/{book['id']}/ch{number}.svg"
            for paragraph in range(1, len(chapter["paragraphs"]) + 1):
                current = found.get(paragraph, current)
                scenes.append(current)
            index[f"{book['id']}/{number}"] = scenes
            print(f"{book['id']}/ch{number}: {len(found)} scenes for {len(chapter['paragraphs'])} paragraphs")

    OUT.write_text(
        "// Generated by tools/build_scene_index.py. Do not edit by hand.\n"
        f"window.SCENES = {json.dumps(index, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
